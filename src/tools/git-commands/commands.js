const ROWS = Object.entries(SECTIONS).flatMap(([group, commands]) =>
    commands.map(([title, summary, command, parts, note]) => ({ group, title, summary, command, parts, note })),
)

// Gives every command a stable key from its title.
export const COMMANDS = ROWS.map((entry) => ({
    ...entry,
    id: entry.title
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, ''),
}))

// Every word typed must appear somewhere in the entry, so "log author" narrows the list.
export function filterCommands(query, group) {
    const words = query.toLowerCase().split(/\s+/).filter(Boolean)

    return COMMANDS.filter((entry) => {
        if (group !== 'all' && entry.group !== group) return false
        if (words.length === 0) return true

        const haystack = [
            entry.title,
            entry.summary,
            entry.command,
            GROUP_NAMES[entry.group],
            ...entry.parts.flat(),
            entry.note ?? '',
        ]
            .join(' ')
            .toLowerCase()
        return words.every((word) => haystack.includes(word))
    })
}