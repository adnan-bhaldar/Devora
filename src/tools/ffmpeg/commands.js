const ROWS = Object.entries(SECTIONS).flatMap(([group, recipes]) =>
    recipes.map(([title, summary, command, parts, note]) => ({ group, title, summary, command, parts, note })),
)

// Gives every recipe a stable key from its title.
export const RECIPES = ROWS.map((recipe) => ({
    ...recipe,
    id: recipe.title
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, ''),
}))

// Every word typed must appear somewhere in the recipe, so "gif palette" narrows the list.
export function filterRecipes(query, group) {
    const words = query.toLowerCase().split(/\s+/).filter(Boolean)

    return RECIPES.filter((recipe) => {
        if (group !== 'all' && recipe.group !== group) return false
        if (words.length === 0) return true

        const haystack = [
            recipe.title,
            recipe.summary,
            recipe.command,
            GROUP_NAMES[recipe.group],
            ...recipe.parts.flat(),
            recipe.note ?? '',
        ]
            .join(' ')
            .toLowerCase()
        return words.every((word) => haystack.includes(word))
    })
}